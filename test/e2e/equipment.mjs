import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch({ headless:true, channel:'chrome' });
try {
 const page = await browser.newPage({ viewport:{width:1440,height:1000} });
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5190');
 await page.locator('canvas').waitFor();
 await page.waitForTimeout(1500);
 const canvas=await page.locator('canvas').elementHandle();
 const trigger=page.getByRole('button',{name:'担当者に相談：バルガス',exact:true});
 await trigger.click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(trigger).toBeFocused();
 if(!await canvas.evaluate(el=>el===document.querySelector('canvas')))throw Error('Conversation replaced factory canvas');
 await trigger.click();
 await page.locator('.conversation-stage img').evaluate(img=>img.decode());
 await page.screenshot({path:'test/e2e/factory-conversation.png',fullPage:true});
 await page.getByRole('button',{name:'会話を閉じる',exact:true}).click();
 await page.getByRole('button',{name:'培養を開始する',exact:true}).click();
 await expect(page.getByRole('button',{name:'製造ライン稼働中',exact:true})).toBeDisabled();
 await page.getByRole('heading',{name:'完成個体 No.1',exact:true}).waitFor({timeout:10000});
 await page.getByRole('button',{name:'品質検査装置を選択',exact:true}).click();
 await expect(page.locator('.equipment-actions')).toContainText('火炎自傷：8');
 await page.getByRole('button',{name:'出撃ゲートを選択',exact:true}).click();
 await page.getByRole('button',{name:'出撃する個体を確認',exact:true}).click();
 await expect(page.getByRole('button',{name:'自動戦闘を実行',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'工場へ戻る',exact:true}).click();
 await page.getByRole('button',{name:'階段 → 研究フロア',exact:true}).click();
 await page.getByRole('button',{name:'担当者に相談：オルフェン',exact:true}).click();
 await page.getByRole('button',{name:'次へ',exact:true}).click();
 await page.getByRole('button',{name:'次へ',exact:true}).click();
 await page.locator('dialog .dialogue-actions button').last().click();
 await expect(page.getByRole('dialog')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'石殻',exact:true})).toBeVisible();
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS: consultation focus/close/canvas preservation, equipment production/inspection/dispatch, dialogue navigation');
} finally { await browser.close(); }
